// Copies the OCR engine and the Polish model into web/public/ocr, so the browser loads them from
// our own domain (no third-party CDN; the document itself never leaves the browser anyway).
import { copyFileSync, mkdirSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const nm = join(root, "node_modules");
const out = join(root, "web", "public", "ocr");
mkdirSync(join(out, "core"), { recursive: true });
mkdirSync(join(out, "lang"), { recursive: true });

copyFileSync(join(nm, "tesseract.js", "dist", "worker.min.js"), join(out, "worker.min.js"));
for (const f of readdirSync(join(nm, "tesseract.js-core"))) {
  if (/^tesseract-core.*\.(js|wasm)$/.test(f)) copyFileSync(join(nm, "tesseract.js-core", f), join(out, "core", f));
}
// "best_int": better accuracy on scans than "fast", still small (about 2.6 MB).
copyFileSync(join(nm, "@tesseract.js-data", "pol", "4.0.0_best_int", "pol.traineddata.gz"), join(out, "lang", "pol.traineddata.gz"));
// Default letter template (generated by scripts/make_letter_template.py) for the browser app.
mkdirSync(join(root, "web", "public", "templates"), { recursive: true });
copyFileSync(join(root, "..", "templates", "wezwanie_do_zaplaty.docx"), join(root, "web", "public", "templates", "domyslny.docx"));
console.log("OCR assets and default template copied to web/public");
